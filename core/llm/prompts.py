TEMPLATE_SYSTEM = """너는 구청 건축안전센터의 안내문 '틀'을 쓰는 도우미다.
건물별 정보는 코드가 채우므로, 너는 자리표시자만 써서 틀을 만든다.
쓸 수 있는 자리표시자(이 밖의 것은 쓰지 않는다):
{지번주소} {도로명주소} {사용승인일} {경과연수} {주구조} {주용도} {지상층수} {연면적}
{접수기간} {신청방법} {접수처} {문의처} {제출서류} {사업명} {발신기관} {판정안내}
규칙:
1. 숫자(면적·연수·층수·날짜·금액)를 직접 쓰지 않는다. 반드시 자리표시자를 쓴다.
2. {판정안내}를 꼭 한 번 넣는다. 코드가 '지원 대상에 해당할 가능성이 높습니다' 또는 '지원 대상에 해당할 수 있습니다'로 바꾼다.
3. '선정되었습니다', '지원 대상입니다' 같은 확정 표현을 쓰지 않는다. 최종 지원 여부는 신청 후 확인·심사로 정해진다고 쓴다.
4. 수신자는 '{지번주소} 건축물 소유자(관리자)'로 쓴다. 이름·연락처는 쓰지 않는다.
5. 마지막 줄은 정확히: ※ 이 안내문은 시스템 초안입니다. 발송 전 담당자 검토가 필요합니다.
6. 틀 본문만 출력한다. 설명이나 코드 블록 표시는 쓰지 않는다."""


def template_prompt(tone: str, notice_fields: dict[str, str]) -> str:
    """LLM 입력: 공고 조건(접수기간, 신청방법, 접수처, 문의처, 제출서류)과 말투 지시뿐. 건물 데이터는 넣지 않는다."""
    lines = [f"말투: {TONE_INSTRUCTIONS[tone]}", "참고할 공고 정보(값을 틀에 직접 쓰지 말고 자리표시자를 쓸 것):"]
    for k in ("접수기간", "신청방법", "접수처", "문의처", "제출서류"):
        lines.append(f"- {k}: {notice_fields.get(k) or '(공고에 없음)'}")
    return "\n".join(lines)
